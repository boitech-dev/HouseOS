"""Themes → CSS. Base goes in the `tokens` layer on `:root` (so an unknown or missing theme still
draws), every other theme in the `theme` layer on `[data-theme="<id>"]`; each block is complete."""

import hashlib
import json
import re
from pathlib import Path

from . import tokens as t

GENERATED = Path(__file__).resolve().parents[3] / "frontend/src/design/generated"
HEADER = "Generated by `python3 -m houseos.theme_kit build` from themes/. Do not edit."
DEFAULT = "zabiwa"
# The pickers' order: Zabiwa first, then the calm themes, the worlds, and Legacy last (any other
# bundled theme after them).
PICKER = ("zabiwa", "pure", "modular", "linen-morning", "y2k", "night-castle", "pocket-hatchling",
          "sento-night", "showa-platform", "carved-night")  # fmt: skip


def bundled(root: Path | None = None) -> list[t.Theme]:
    root = root or t.ROOT
    found = sorted(
        p.name
        for p in root.iterdir()
        if p.is_dir() and not p.name.startswith("_") and (p / "theme.json").exists()
    )
    return [t.load(name, root) for name in sorted(found, key=lambda n: (n != "base", PICKER.index(n) if n in PICKER else len(PICKER), n))]


def block(selector: str, values: dict[str, str], scheme: str | None = None) -> str:
    lines = [f"  {name}: {value};" for name, value in values.items()]
    if scheme:
        lines.insert(0, f"  color-scheme: {scheme};")
    return selector + " {\n" + "\n".join(lines) + "\n}\n"


ART = re.compile(r"url\(\s*([\"']?)art/")


def theme_css(theme: t.Theme, base: t.Theme, art: str = "") -> str:
    """One theme's rules (all its schemes and rooms), unwrapped. `art`: where its art/ is served,
    so a texture's url(art/…) finds its file."""
    out = []
    for index, scheme in enumerate(theme.schemes):
        values = t.variables(theme, scheme, base)
        values = {k: ART.sub(lambda m: f"url({m[1]}{art}art/", v) for k, v in values.items()}
        scheme_part = "" if index == 0 else f'[data-scheme="{scheme}"]'
        if theme.id == base.id:
            owners = [f":root{scheme_part}", f'[data-theme="base"]{scheme_part}']
        else:
            owners = [f'[data-theme="{theme.id}"]{scheme_part}']
        out.append(block(", ".join(owners), values, scheme))
        for room, room_values in t.room_variables(values).items():
            out.append(block(", ".join(f'{o}[data-room="{room}"]' for o in owners), room_values))
    return "\n".join(out)


# Fontsource's subsets: the ranges a browser uses to fetch only the file it needs.
RANGES = {
    "latin": "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, "
    "U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
    "latin-ext": "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, "
    "U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, "
    "U+2C60-2C7F, U+A720-A7FF",
}
FONT_FILE = re.compile(r"(.+?)-(latin-ext|latin)-(\d{3})-(normal|italic)\.woff2")


def font_faces(theme: t.Theme, url: str) -> str:
    """@font-face for the theme's own fonts/ files, served at `url` + file name."""
    folder = theme.folder / "fonts"
    families = {re.sub(r"[^a-z0-9]+", "-", f.lower()).strip("-"): f for f in theme.manifest["fonts"].values()}
    faces = []
    for font in sorted(folder.glob("*.woff2")) if folder.is_dir() else []:
        found = FONT_FILE.fullmatch(font.name)
        if found and found[1] in families:
            faces.append(
                f'@font-face {{ font-family: "{families[found[1]]}"; font-style: {found[4]}; '
                f"font-weight: {found[3]}; font-display: swap; src: url({url}{font.name}) "
                f'format("woff2"); unicode-range: {RANGES[found[2]]}; }}\n'
            )
    return "".join(faces)


def stylesheet(themes: list[t.Theme]) -> str:
    base = themes[0]
    parts = [f"/* {HEADER} */\n", "@layer tokens {\n" + indent(theme_css(base, base)) + "}\n"]
    rest = [indent(theme_css(theme, base, f"../../../../themes/{theme.id}/")) for theme in themes[1:]]
    if rest:
        parts.append("@layer theme {\n" + "\n".join(rest) + "}\n")
    # A bundled theme's own fonts, from its folder (Vite bundles them from this relative path).
    parts += [font_faces(theme, f"../../../../themes/{theme.id}/fonts/") for theme in themes]
    return "\n".join(part for part in parts if part)


def indent(css: str) -> str:
    return "".join("  " + line if line.strip() else line for line in css.splitlines(keepends=True))


def entry(theme: t.Theme, base: t.Theme) -> dict:
    """What the interface knows of one theme (the picker's names, swatches, slots and words)."""
    m = theme.manifest
    swatches = {}
    for scheme in theme.schemes:
        v = t.variables(theme, scheme, base)
        swatches[scheme] = [v[k] for k in SWATCHES]
    return {
        "id": theme.id,
        "names": m["names"],
        "description": m["description"],
        "schemes": theme.schemes,
        "hidden": bool(m.get("hidden")),
        "identity": m.get("identity", "line"),
        "slots": m.get("slots", {}),
        "layers": m.get("layers", []),
        "credit": m.get("credit"),
        # The pickers' card: the tour's picture of Home in each scheme (art/card-<scheme>.webp).
        "cards": {s: f"art/card-{s}.webp" for s in theme.schemes if (theme.folder / f"art/card-{s}.webp").is_file()},
        "parts": {**PARTS_DEFAULT, **(m.get("parts") or {})},
        "sprites": sprite_grids(theme),
        "flavor": {k: v for k, v in t.read(theme.folder / "flavor.json").items() if not k.startswith("$")},
        "swatches": swatches,
    }


PARTS_DEFAULT = {
    part: spec["default"]
    for part, spec in t.read(t.ROOT / "_schema/parts.json").items()
    if not part.startswith("$")
}


def sprite_grids(theme: t.Theme) -> dict:
    """The pieces this theme redraws (sprites.json as checked): its palette, letter → color.sprite
    token, and its grids by piece id. The app paints them in the theme's colours."""
    data = t.read(theme.folder / "sprites.json")
    if not data:
        return {}
    return {"palette": data.get("palette", {}), "glyphs": data.get("glyphs", {})}


# What a picker's card shows: the ground, the ink, the accent, a state and a room that is not
# the accent (Listen often is), so five dots say five different things.
SWATCHES = (
    "--c-bg-canvas",
    "--c-fg-default",
    "--c-accent-solid",
    "--c-success-solid",
    "--c-room-watch",
)


def poke_at(poke: dict, at) -> dict:
    burst = poke.get("burst")
    return {**poke, **({"image": at(poke["image"])} if "image" in poke else {}),
            **({"burst": {**burst, "image": at(burst["image"])}} if burst else {})}  # fmt: skip


def served(info: dict, where: str, folder: Path | None = None) -> dict:
    """A theme's entry with its pictures (slots, rooms' pictures, layers) where the app serves its
    art/: `where` is "/themes/bundled/<id>/" for a bundled theme, "/themes/<id>/" for an installed one.
    With the theme's `folder`, each picture's address carries a fingerprint of its content
    (?v=…): a picture redrawn under the same name is fetched again, never mixed with a cached one."""

    def at(path: str) -> str:
        if not path.startswith("art/"):
            return path
        file = folder / path if folder else None
        mark = f"?v={hashlib.sha256(file.read_bytes()).hexdigest()[:10]}" if file and file.is_file() else ""
        return where + path + mark

    def fill_at(fill):
        if isinstance(fill, str):
            return at(fill)
        if isinstance(fill, dict) and "image" in fill:
            at_any = lambda file: at(file) if isinstance(file, str) else {s: at(f) for s, f in file.items()}  # noqa: E731
            more = {key: {k: at_any(file) for k, file in fill[key].items()} for key in ("rooms", "schemes") if key in fill}
            return {**fill, "image": at(fill["image"]), **more}
        return fill

    return info | {
        "cards": {scheme: at(file) for scheme, file in info.get("cards", {}).items()},
        "slots": {slot: fill_at(fill) for slot, fill in info["slots"].items()},
        "layers": [{**layer, "image": at(layer["image"]), **({"poke": poke_at(layer["poke"], at)} if "poke" in layer else {})}
                   for layer in info["layers"]],
    }


