def catalogue_of(name: str) -> dict:
    return {k: v for k, v in t.read(t.ROOT / "_schema" / name).items() if not k.startswith("$")}


def slot_catalogue() -> dict:
    return {k: v for k, v in t.read(t.ROOT / "_schema/slots.json").items() if not k.startswith("$")}


def token_schema(base: t.Theme) -> str:
    """themes/_schema/tokens.schema.json: every name a theme may set (a typo or a fixed token is
    refused by an editor as well as by the checks), made from the catalogue so it never drifts."""
    tree: dict = {}
    for row in t.catalogue(base):
        if row["themeable"] == "no":
            continue
        node = tree
        for part in row["token"].split(".")[:-1]:
            node = node.setdefault(part, {})
        node[row["token"].split(".")[-1]] = row["description"]

    def schema(node):
        if isinstance(node, str):
            return {
                "type": "object",
                "description": node,
                "required": ["$value"],
                "properties": {"$value": {}, "$type": {"type": "string"}, "$description": {"type": "string"}},
                "additionalProperties": False,
            }
        props = {key: schema(child) for key, child in node.items()}
        return {
            "type": "object",
            "properties": {"$type": {"type": "string"}, "$description": {"type": "string"}, **props},
            "additionalProperties": False,
        }

    top = schema(tree)
    top["properties"]["$schema"] = {"type": "string"}
    return (
        json.dumps(
            {
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "$comment": HEADER,
                "title": "A HouseOS theme's tokens.json (DTCG): only what differs from Base",
                **top,
            },
            indent=1,
            ensure_ascii=False,
        )
        + "\n"
    )


def manifest_schema() -> str:
    """themes/_schema/theme.schema.json with its parts, slot fills and layers made from what the
    checks accept (parts.json, check.LAYER), so an editor's hints never drift from the kit."""
    from . import check

    schema = json.loads((t.ROOT / "_schema/theme.schema.json").read_text())
    props = schema["properties"]
    props.pop("motion", None)
    props["credit"] = {"$ref": "#/$defs/words", "description": "Who made it, shown small at the rail's foot: plain text, 40 characters at most, never a link."}
    props["parts"]["properties"] = {
        part: {"enum": list(spec["variants"]), "default": spec["default"],
               "description": "; ".join(f"{name}: {what}" for name, what in spec["variants"].items())}
        for part, spec in catalogue_of("parts.json").items()
    }  # fmt: skip
    image = props["slots"]["additionalProperties"]["oneOf"][2]["properties"]
    image["fit"]["enum"] = ["cover", "contain", "stretch", "slice"]
    image["slice"] = {"type": "integer", "minimum": 1, "maximum": 400, "description": "With fit slice (surfaces): the frame's corner size in px."}
    picture = {"type": "string", "pattern": image["image"]["pattern"]}
    image["rooms"] = {"type": "object", "propertyNames": {"enum": list(t.ALL_ROOMS)},
                      "additionalProperties": {"oneOf": [picture, {"type": "object", "additionalProperties": picture,
                                                                   "propertyNames": {"enum": list(t.SCHEMES)}}]},
                      "description": "Another picture in these rooms: {room: art/<file>} or {room: {dark|light: art/<file>}}."}  # fmt: skip
    image["schemes"] = {"type": "object", "propertyNames": {"enum": list(t.SCHEMES)},
                        "additionalProperties": {"type": "string", "pattern": image["image"]["pattern"]},
                        "description": "Another picture in this scheme: {dark|light: art/<file>} (a room's own wins)."}  # fmt: skip
    number = lambda low, high: {"type": "number", "minimum": low, "maximum": high}  # noqa: E731
    props["layers"] = {
        "type": "array", "maxItems": check.LAYERS_MAX,
        "description": "Pictures the app moves, as far as the person's motion level allows (themes/README.md, Layers).",
        "items": {"type": "object", "required": ["image", "where"], "additionalProperties": False, "properties": {
            "image": image["image"],
            **{key: {"enum": list(allowed)} for key, allowed in check.LAYER.items()},
            "rooms": {"type": "array", "items": {"enum": list(t.ALL_ROOMS)}},
            "schemes": {"type": "array", "items": {"enum": list(t.SCHEMES)}},
            "scale": {"type": "integer", "minimum": 1, "maximum": 8},
            "opacity": number(0.05, 1), "depth": number(0, 1),
            "above": {"type": "boolean", "description": f"Over the page (where page), opacity {check.ABOVE_OPACITY} at most."},
            "under": {"type": "boolean", "description": "Behind the place's own picture (page, hero, status, header), e.g. a sky seen through it."},
            "drift": {"type": "array", "items": number(-200, 200), "minItems": 2, "maxItems": 2},
            "cross": {"type": "object", "additionalProperties": False, "properties": {
                "seconds": number(2, 120), "every": number(2, 600), "from": {"enum": list(check.CROSS_FROM)}}},
            "frames": {"type": "object", "additionalProperties": False, "properties": {
                "count": {"type": "integer", "minimum": 2, "maximum": 32}, "fps": number(1, 24)}},
            "particles": {"type": "object", "additionalProperties": False, "properties": {
                "count": {"type": "integer", "minimum": 1, "maximum": 24},
                "motion": {"enum": list(check.PARTICLE_MOTION)}, "seconds": number(2, 60)}},
            "playing": {"type": "boolean"},
            "poke": {"type": "object", "additionalProperties": False, "required": ["frames"],
                     "description": "Desktop: a click plays this reaction once (a natural piece), with an optional small burst.",
                     "properties": {"image": image["image"], "frames": {"type": "object", "additionalProperties": False, "properties": {
                         "count": {"type": "integer", "minimum": 2, "maximum": 32}, "fps": number(1, 24)}},
                         "stay": {"enum": ["random"], "description": "After the reaction, the piece keeps one of its frames at random (a new arrangement each click)."},
                         "burst": {"type": "object", "additionalProperties": False, "required": ["image", "count"], "properties": {
                             "image": image["image"], "count": {"type": "integer", "minimum": 1, "maximum": check.BURST_MAX}}}}},
        }},
    }  # fmt: skip
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def build(root: Path | None = None, out: Path = GENERATED) -> dict[str, str]:
    """The generated files by name (written when `out` is given; the schema beside the themes)."""
    root = root or t.ROOT
    themes = bundled(root)
    files = {"themes.css": stylesheet(themes), "themes.ts": registry(themes)}
    if out:
        out.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (out / name).write_text(text)
        (root / "_schema/tokens.schema.json").write_text(token_schema(themes[0]))
        (root / "_schema/theme.schema.json").write_text(manifest_schema())
    return files
