def sticker(motif):
    """A die-cut sticker, 16 × 16: the motif (≤ 12 × 12, its own outline) centred, a white border
    all round (8 neighbours, so the cut is rounded) and a plum outline outside that (4 neighbours)."""
    h, w = len(motif), max(map(len, motif))
    assert h <= 12 and w <= 12, (h, w)
    grid = [["."] * 16 for _ in range(16)]
    oy, ox = (16 - h) // 2, (16 - w) // 2
    for y, row in enumerate(motif):
        for x, ch in enumerate(row):
            if ch != ".":
                grid[oy + y][ox + x] = ch
    def ring(letter, near):
        add = []
        for y in range(16):
            for x in range(16):
                if grid[y][x] == "." and any(0 <= y + dy < 16 and 0 <= x + dx < 16 and grid[y + dy][x + dx] != "."
                                             for dx, dy in near):
                    add.append((y, x))
        for y, x in add:
            grid[y][x] = letter
    ring("P", [(dx, dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy])
    ring("k", [(1, 0), (-1, 0), (0, 1), (0, -1)])
    return ["".join(r) for r in grid]

