def over(grid, piece, x0, y0):
    """Lay a little piece ('.' clear) on a grid at (x0, y0)."""
    rows = [list(r) for r in grid]
    for y, row in enumerate(piece):
        for x, ch in enumerate(row):
            if ch != ".":
                rows[y0 + y][x0 + x] = ch
    return ["".join(r) for r in rows]


