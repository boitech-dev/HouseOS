def pip(face, sprout="up", chin=CHIN, top=TOP):
    """Pip from its parts: 3 rows of sprout, 2 of head top, 4 of face, 1 chin, 6 of shell."""
    return SPROUTS[sprout] + top + face + chin + SHELL

