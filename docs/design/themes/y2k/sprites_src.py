def egg(face, left=".", right="."):
    """Nox with a 6 x 4 LCD face (rows of P, i or p)."""
    assert len(face) == 4 and all(len(r) == 6 for r in face), face
    return EGG_TOP + [f"{left}.kCk{row}kVk.{right}" for row in face] + EGG_BOTTOM


