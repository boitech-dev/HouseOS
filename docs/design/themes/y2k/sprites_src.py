def check():
    bad = []
    for name, rows in GLYPHS.items():
        w = len(rows[0])
        for i, row in enumerate(rows):
            if len(row) != w:
                bad.append(f"{name} row {i}: {len(row)} != {w}")
            for ch in row:
                if ch != "." and ch not in PALETTE:
                    bad.append(f"{name} row {i}: letter {ch!r}")
        if w > 16 or len(rows) > 16:
            bad.append(f"{name}: larger than 16")
    if bad:
        raise SystemExit("\n".join(bad))


