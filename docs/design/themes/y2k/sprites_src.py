def preview(out):
    from PIL import Image, ImageDraw

    names = list(GLYPHS)
    cell, z = 72, 4
    cols = 8
    rows = (len(names) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * cell * 2 + 8, rows * cell), "#222")
    for s, scheme in enumerate(PREVIEW):
        pal = PREVIEW[scheme]
        for n, name in enumerate(names):
            x0 = s * (cols * cell + 8) + (n % cols) * cell
            y0 = (n // cols) * cell
            d = ImageDraw.Draw(sheet)
            d.rectangle([x0, y0, x0 + cell - 2, y0 + cell - 2], fill=pal["bg"])
            g = GLYPHS[name]
            ox = x0 + (cell - len(g[0]) * z) // 2
            oy = y0 + (cell - len(g) * z) // 2
            for y, row in enumerate(g):
                for x, ch in enumerate(row):
                    if ch != ".":
                        d.rectangle([ox + x * z, oy + y * z, ox + x * z + z - 1, oy + y * z + z - 1], fill=pal[ch])
